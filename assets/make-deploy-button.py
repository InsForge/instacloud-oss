#!/usr/bin/env python3
"""Regenerate assets/deploy-button.svg.

A one-shot design tool, not part of any build: nothing in CI runs it, and the SVG it writes is
the committed artifact. It exists because the label is OUTLINED rather than set as <text>, which
is what keeps the button a fixed width on every machine (and is what Railway, Zeabur and Sealos
all do with theirs). Outlines cannot be edited by hand, so changing the wording, the size or the
face means running this again.

Requires, none of them repo dependencies:

    python3 -m venv .venv && .venv/bin/pip install fonttools brotli uharfbuzz
    npm pack @fontsource/inter && tar xzf fontsource-inter-*.tgz

Then, from this directory:

    .venv/bin/python make-deploy-button.py package/files/inter-latin-500-normal.woff2

harfbuzz does the shaping so the letter spacing matches what a browser would produce from the
same font, kerning included. Inter is the brand face and is licensed under the SIL OFL 1.1,
which is what makes embedding its outlines here redistributable.
"""
