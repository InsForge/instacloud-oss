def outline(font_path: Path, text: str, size: float) -> tuple[str, float, float]:
    """Shape `text` and return (single path d, advance width, cap height), baseline at y=0."""
    # harfbuzz cannot read woff2, so hand it a ttf either way.
    if font_path.suffix == ".woff2":
        tmp = Path(tempfile.mkdtemp()) / "font.ttf"
        f = TTFont(font_path)
        f.flavor = None
        f.save(tmp)
        font_path = tmp

    face = hb.Face(hb.Blob(font_path.read_bytes()))
    hb_font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb_font, buf)

    tt = TTFont(font_path)
    glyphs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    scale = size / tt["head"].unitsPerEm

    parts, x = [], 0.0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}")
        # Font units go up, SVG goes down, so y is flipped and the baseline sits at y=0.
        glyphs[order[info.codepoint]].draw(
            TransformPen(pen, Transform(scale, 0, 0, -scale,
                                        x + pos.x_offset * scale, -pos.y_offset * scale))
        )
        if pen.getCommands():
            parts.append(pen.getCommands())
        x += pos.x_advance * scale
    return " ".join(parts), x, tt["OS/2"].sCapHeight * scale


def main() -> None:
    font = Path(sys.argv[1] if len(sys.argv) > 1 else "package/files/inter-latin-500-normal.woff2")
    text_d, text_w, cap_h = outline(font, LABEL, FONT_SIZE)

    icon_scale = ICON_HEIGHT / ICON_BOX[1]
    icon_w = ICON_BOX[0] * icon_scale
    text_x = PAD_LEFT + icon_w + GAP
    width = text_x + text_w + PAD_RIGHT
    icon_y = (HEIGHT - ICON_HEIGHT) / 2
    baseline = (HEIGHT + cap_h) / 2   # centred on cap height, as the reference buttons are

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0f}" height="{HEIGHT:.0f}" viewBox="0 0 {width:.0f} {HEIGHT:.0f}" role="img" aria-label="{LABEL}">
  <title>{LABEL}</title>
  <!--
    Generated by assets/make-deploy-button.py. The label is outlined, so do not edit it by hand:
    change the constants in that script and run it again.

    One file covers both themes, swapped by a prefers-color-scheme rule INSIDE the SVG rather than
    by a <picture> around it. The README this button lives in is also served by the template
    gallery, whose markdown renderer parses no raw HTML on purpose, so there is no <picture> to
    reach for. An SVG referenced from <img> still evaluates the query against the viewer's own
    system setting, which is how templates/pi/logo.svg already covers light and dark with one
    asset. A renderer that ignores the query keeps the light palette, so the fallback is brand
    black. Without the rule the black button all but vanishes on a dark README.

    Geometry follows the one-click buttons this sits beside (Railway 183x40 r6, Sealos 185x42
    r6.7, Zeabur 172x36 r8): {HEIGHT:.0f} tall, {RADIUS:.0f} radius, {PAD_LEFT:.0f}/{GAP:.0f}/{PAD_RIGHT:.0f} padding. It is wider than
    those only because "{LABEL}" is four characters longer than "Deploy on Railway".

    Label: Inter Medium (SIL OFL 1.1, the brand face) shaped with harfbuzz at {FONT_SIZE:.0f}px,
    cap height {cap_h:.2f}px.
  -->
  <style>
    .bg {{ fill: #0A0A0A }}
    .fg {{ fill: #FAFAFA }}
    @media (prefers-color-scheme: dark) {{
      .bg {{ fill: #FAFAFA }}
      .fg {{ fill: #0A0A0A }}
    }}
  </style>
  <rect class="bg" width="{width:.0f}" height="{HEIGHT:.0f}" rx="{RADIUS:.0f}"/>
  <g class="fg" transform="translate({PAD_LEFT:.0f} {icon_y:.0f}) scale({icon_scale:.6f})">
    <path d="{ICON_PATH}"/>
  </g>
  <path class="fg" transform="translate({text_x:.2f} {baseline:.2f})" d="{text_d}"/>
</svg>
"""
    out = Path(__file__).with_name("deploy-button.svg")
    out.write_text(svg)
    print(f"{out.name}: {width:.0f}x{HEIGHT:.0f} r{RADIUS:.0f}, label {text_w:.2f}px, cap {cap_h:.2f}px")


if __name__ == "__main__":
    main()
